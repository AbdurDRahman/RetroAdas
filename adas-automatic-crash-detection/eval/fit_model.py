#!/usr/bin/env python3
"""Fit the linear crash score on the VZCrash TRAIN shards (+ every capture
from the continuous-driving datasets as extra negatives) and write
src/crash_model.h. Never touches the test split.

    .venv\\Scripts\\python eval\\fit_model.py            # fit + write header + rebuild
    .venv\\Scripts\\python eval\\fit_model.py --dry-run  # fit, print, do not write

Model: logistic regression on log1p(features), class-weighted so crashes
and negatives count equally. The operating threshold is chosen on the
train split's own validation fold to hit the agreed target: the highest
threshold at which recall on tier-2+ (peak ≥ 3 g) crashes is ≥ 95 % — the
severe tier is covered by the physics override regardless. The test-split
numbers in evaluation.md are then an honest out-of-sample measurement.
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import train_test_split

sys.path.insert(0, str(Path(__file__).resolve().parent))
import datasets as ds  # noqa: E402
from engine import FEAT_NAMES, NFEAT, Engine, build  # noqa: E402

HDR = ds.ROOT / "src" / "crash_model.h"
CACHE = ds.ROOT / "build" / "train_features.npz"


def collect(quick: int | None):
    """Feature rows of every capture, with label per row (1 crash, 0 not)
    and the event's peak_a tier for the threshold selection."""
    X, y, grp, tier_peak = [], [], [], []
    e = Engine()
    n_ev = 0
    t0 = time.time()
    for shard, eid, lab, acc, gyr, spd, vs in ds.iter_vzcrash("train"):
        n_ev += 1
        if quick and n_ev > quick:
            break
        e.reset()
        _, feats = e.run(acc, gyr)
        if not len(feats):
            continue
        # one row per event: the strongest capture (that is what the device acts on
        # first in practice is the first; using the strongest makes the label clean)
        k = int(np.argmax(feats[:, 0]))
        X.append(feats[k]); y.append(1 if lab == 0 else 0); grp.append(f"vz:{lab}")
        tier_peak.append(float(feats[k, 0]))
        if n_ev % 5000 == 0:
            print(f"  {n_ev} train events, {len(X)} rows, {time.time() - t0:.0f} s", file=sys.stderr)
    print(f"VZCrash train: {n_ev} events -> {len(X)} capture rows", file=sys.stderr)
    # continuous driving negatives (captures that reach the pre-trigger on real roads)
    extra = 0
    for d in list(ds.iter_pvs()) + list(ds.iter_roadsens()):
        e.reset()
        _, feats = e.run(d.acc, d.gyr, max_feat=4096)
        for f in feats:
            X.append(f); y.append(0); grp.append(d.meta["source"]); tier_peak.append(float(f[0]))
            extra += 1
    print(f"continuous-driving negatives: {extra} capture rows", file=sys.stderr)
    return np.array(X, np.float32), np.array(y), np.array(grp), np.array(tier_peak)


def fit(X, y, grp, tier_peak, seed=0):
    Z = np.log1p(np.clip(X, 0, None))
    Ztr, Zva, ytr, yva, ptr, pva = train_test_split(Z, y, tier_peak, test_size=0.25,
                                                    random_state=seed, stratify=y)
    clf = LogisticRegression(class_weight="balanced", C=1.0, max_iter=2000)
    clf.fit(Ztr, ytr)
    w, b = clf.coef_[0], float(clf.intercept_[0])
    s_va = Zva @ w + b
    # threshold: highest value giving >= 95% recall on moderate+ crashes (peak >= 3 g)
    mod = (yva == 1) & (pva >= 3.0)
    cand = np.sort(s_va[mod])
    thr = float(cand[int(0.05 * len(cand))]) if len(cand) else 0.0
    fired = s_va >= thr
    rep = {
        "n_train": int(len(ytr)), "n_val": int(len(yva)),
        "val_recall_all": float(fired[yva == 1].mean()),
        "val_recall_mod": float(fired[mod].mean()) if mod.any() else float("nan"),
        "val_recall_sev": float(fired[(yva == 1) & (pva >= 4.0)].mean()) if ((yva == 1) & (pva >= 4.0)).any() else float("nan"),
        "val_fpr": float(fired[yva == 0].mean()),
        "thr": thr,
    }
    return w, b, thr, rep


def write_header(w, b, thr, rep, version):
    lines = [
        "/*",
        " * crash_model.h — fitted linear crash score. GENERATED by eval/fit_model.py;",
        " * edit that script, not this file. The engine computes",
        " *",
        " *     score = CRASH_MODEL_BIAS + sum_i CRASH_MODEL_W[i] * log1p(f[i])",
        " *",
        " * over the CRASH_NFEAT features in the order of crash_feat_t, and raises",
        " * EV_CRASH when score >= CRASH_MODEL_THRESHOLD (or the physics override",
        " * fires).",
        " *",
        f" * Fitted on VZCrash train ({rep['n_train']} rows) + continuous-driving negatives;",
        f" * held-out fold: recall all {rep['val_recall_all']:.1%}, moderate+ {rep['val_recall_mod']:.1%},",
        f" * severe {rep['val_recall_sev']:.1%}, FPR {rep['val_fpr']:.2%} at threshold {thr:.3f}.",
        " */",
        "#ifndef CRASH_MODEL_H",
        "#define CRASH_MODEL_H",
        "",
        f'#define CRASH_MODEL_VERSION "{version}"',
        "",
        "/* order: " + ", ".join(FEAT_NAMES) + " */",
        "static const float CRASH_MODEL_W[%d] = {" % NFEAT,
        "    " + ", ".join(f"{v:.6f}f" for v in w),
        "};",
        f"static const float CRASH_MODEL_BIAS = {b:.6f}f;",
        f"static const float CRASH_MODEL_THRESHOLD = {thr:.6f}f;",
        "",
        "#endif /* CRASH_MODEL_H */",
        "",
    ]
    HDR.write_text("\n".join(lines), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--quick", type=int, default=None, help="use only N train events")
    ap.add_argument("--no-cache", action="store_true")
    args = ap.parse_args()
    if not ds.vzcrash_shards("train"):
        raise SystemExit("no train shards in data/vzcrash — run download_vzcrash.py --train 2")
    if CACHE.exists() and not args.no_cache and not args.quick:
        z = np.load(CACHE, allow_pickle=True)
        X, y, grp, tp = z["X"], z["y"], z["grp"], z["tp"]
        print(f"loaded cached features {X.shape}", file=sys.stderr)
    else:
        X, y, grp, tp = collect(args.quick)
        if not args.quick:
            CACHE.parent.mkdir(exist_ok=True)
            np.savez(CACHE, X=X, y=y, grp=grp, tp=tp)
    w, b, thr, rep = fit(X, y, grp, tp)
    print("weights:")
    for n, v in zip(FEAT_NAMES, w):
        print(f"  {n:8s} {v:+.3f}")
    print(f"  bias     {b:+.3f}\n  threshold {thr:+.3f}")
    print("held-out fold:", {k: (f"{v:.3%}" if "recall" in k or "fpr" in k else v) for k, v in rep.items()})
    if args.dry_run:
        return
    version = time.strftime("fit-%Y%m%d")
    write_header(w, b, thr, rep, version)
    print(f"wrote {HDR}; rebuilding libcrash")
    build(force=True)
    # keep the firmware copy in step
    import subprocess
    subprocess.run([sys.executable, str(ds.ROOT / "firmware" / "sync_src.py")], check=True)


if __name__ == "__main__":
    main()
